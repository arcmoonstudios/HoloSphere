use num_complex::Complex32;
use serde::{Deserialize, Serialize};
use std::time::Instant;

use crate::VectorEmbedding;

/// Hardware and environment execution profile generated by AutoForge.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PlannerProfile {
    /// Evaluated SIMD FMA throughput (GFLOPs).
    pub simd_gflops: f32,
    /// Measured streaming memory bandwidth (GB/s).
    pub memory_bandwidth_gbps: f32,
    /// Storage page-fault overhead estimate (microseconds).
    pub storage_latency_us: f32,
    /// Empirically calibrated exact-scan crossover scale factor.
    pub crossover_scale: f32,
}

impl Default for PlannerProfile {
    fn default() -> Self {
        Self {
            simd_gflops: 250.0,
            memory_bandwidth_gbps: 45.0,
            storage_latency_us: 2.5,
            crossover_scale: 1.0,
        }
    }
}

pub struct AutoForge;

impl AutoForge {
    /// Calibrates hardware performance and returns a tuned `PlannerProfile`.
    pub fn calibrate() -> PlannerProfile {
        let dim = 512;
        let iters = 1000;

        let v1 = VectorEmbedding::from_complex(
            (0..dim).map(|i| Complex32::new(i as f32, 1.0)).collect(),
        )
        .into_normalized();
        let v2 = VectorEmbedding::from_complex(
            (0..dim).map(|i| Complex32::new(1.0, i as f32)).collect(),
        )
        .into_normalized();

        // 1. Measure SIMD throughput
        let t0 = Instant::now();
        let mut accum = 0.0f32;
        for _ in 0..iters {
            accum += (v1.dot_product_complex(&v2)).re;
        }
        let elapsed_s = t0.elapsed().as_secs_f64().max(1e-7);

        // 8 FLOPs per complex coordinate
        let total_flops = (iters as f64) * (dim as f64) * 8.0;
        let simd_gflops = ((total_flops / elapsed_s) / 1e9) as f32;

        // 2. Measure Memory Bandwidth
        let total_bytes = (iters as f64) * (dim as f64) * 16.0; // 2 vectors * 8 bytes
        let memory_bandwidth_gbps = ((total_bytes / elapsed_s) / 1e9) as f32;

        let crossover_scale = if simd_gflops > 100.0 { 1.2 } else { 0.9 };

        let _ = accum;

        PlannerProfile {
            simd_gflops,
            memory_bandwidth_gbps,
            storage_latency_us: 2.5,
            crossover_scale,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_autoforge_calibration() {
        let profile = AutoForge::calibrate();
        assert!(profile.simd_gflops > 0.1);
        assert!(profile.memory_bandwidth_gbps > 0.01);
        assert!(profile.crossover_scale > 0.0);
    }
}
