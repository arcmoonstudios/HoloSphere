use num_complex::Complex32;
use serde::{Deserialize, Serialize};
use std::time::Instant;

use crate::VectorEmbedding;

/// Hardware and environment execution profile generated by AutoForge.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PlannerProfile {
    /// Evaluated SIMD FMA throughput (GFLOPs).
    pub simd_gflops: f32,
    /// Measured streaming memory bandwidth (GB/s).
    pub memory_bandwidth_gbps: f32,
    /// Storage page-fault overhead estimate (microseconds).
    pub storage_latency_us: f32,
    /// Empirically calibrated exact-scan crossover scale factor.
    pub crossover_scale: f32,
}

impl Default for PlannerProfile {
    fn default() -> Self {
        Self {
            simd_gflops: 250.0,
            memory_bandwidth_gbps: 45.0,
            storage_latency_us: 2.5,
            crossover_scale: 1.0,
        }
    }
}

pub struct AutoForge;

impl AutoForge {
    /// Calibrates hardware performance and returns a tuned `PlannerProfile`.
    pub fn calibrate() -> PlannerProfile {
        let dim = 512;
        let iters = 1000;

        let v1 = VectorEmbedding::from_complex(
            (0..dim).map(|i| Complex32::new(i as f32, 1.0)).collect(),
        )
        .into_normalized();
        let v2 = VectorEmbedding::from_complex(
            (0..dim).map(|i| Complex32::new(1.0, i as f32)).collect(),
        )
        .into_normalized();

        // 1. Measure SIMD throughput
        let t0 = Instant::now();
        let mut accum = 0.0f32;
        for _ in 0..iters {
            accum += (v1.dot_product_complex(&v2)).re;
        }
        let elapsed_s = t0.elapsed().as_secs_f64().max(1e-7);

        // 8 FLOPs per complex coordinate
        let total_flops = (iters as f64) * (dim as f64) * 8.0;
        let simd_gflops = ((total_flops / elapsed_s) / 1e9) as f32;

        // 2. Measure Memory Bandwidth
        let total_bytes = (iters as f64) * (dim as f64) * 16.0; // 2 vectors * 8 bytes
        let memory_bandwidth_gbps = ((total_bytes / elapsed_s) / 1e9) as f32;

        let crossover_scale = if simd_gflops > 100.0 { 1.2 } else { 0.9 };

        let _ = accum;

        PlannerProfile {
            simd_gflops,
            memory_bandwidth_gbps,
            storage_latency_us: 2.5,
            crossover_scale,
        }
    }
}

/// High-level operator intent configuration eliminating low-level manual parameter tuning.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub enum OperatorIntent {
    /// Strict 100% mathematically certified exact Top-K retrieval.
    CertifiedExact,
    /// High-throughput approximate retrieval targeting a specific recall boundary.
    HighRecall { target_recall: f64 },
    /// Latency-budgeted query execution with bounded execution time.
    LatencyBudget { max_micros: u64 },
    /// Memory-constrained footprint with maximal quantization compression.
    ResourceBudget { max_memory_mb: usize },
}

/// Comprehensive high-level operator intent specification.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct OperatorIntentConfig {
    pub contract: String, // "certified" | "approximate"
    pub p99_target_ms: u32,
    pub durability_mode: String, // "quorum" | "local"
    pub max_commit_latency_ms: u32,
    pub memory_budget_gb: usize,
    pub storage_budget_gb: usize,
    pub failure_tolerance: u32,
}

impl Default for OperatorIntentConfig {
    fn default() -> Self {
        Self {
            contract: "certified".to_string(),
            p99_target_ms: 10,
            durability_mode: "quorum".to_string(),
            max_commit_latency_ms: 15,
            memory_budget_gb: 64,
            storage_budget_gb: 1000,
            failure_tolerance: 1,
        }
    }
}

/// Derived physical execution parameters computed by AutoForge.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct DerivedPhysicalConfig {
    pub rivero_profile: String,
    pub proof_tree_fanout: usize,
    pub proof_tree_leaf_capacity: usize,
    pub lutz_code_bits: usize,
    pub worker_threads: usize,
    pub tier0_cache_mb: usize,
    pub tier1_cache_mb: usize,
    pub raft_batch_target: usize,
    pub learner_count: usize,
    pub compaction_rate_mbps: usize,
    pub remote_prefetch_chunks: usize,
}

impl AutoForge {
    /// Synthesizes optimal low-level physical parameters from high-level operator intent.
    pub fn derive_physical_config(intent: &OperatorIntentConfig, profile: &PlannerProfile) -> DerivedPhysicalConfig {
        let is_certified = intent.contract.to_lowercase() == "certified";
        let rivero_profile = if is_certified { "Precision".to_string() } else { "Throughput".to_string() };
        
        let proof_tree_fanout = if profile.simd_gflops > 200.0 { 16 } else { 8 };
        let proof_tree_leaf_capacity = 64;
        let lutz_code_bits = if is_certified { 8 } else { 4 };
        let worker_threads = num_cpus::get().max(4);

        let total_mem_mb = intent.memory_budget_gb * 1024;
        let tier0_cache_mb = (total_mem_mb as f64 * 0.35) as usize;
        let tier1_cache_mb = (total_mem_mb as f64 * 0.50) as usize;

        let raft_batch_target = if intent.max_commit_latency_ms >= 15 { 32 } else { 16 };
        let learner_count = (intent.failure_tolerance as usize * 2).max(1);
        let compaction_rate_mbps = 100;
        let remote_prefetch_chunks = 4;

        DerivedPhysicalConfig {
            rivero_profile,
            proof_tree_fanout,
            proof_tree_leaf_capacity,
            lutz_code_bits,
            worker_threads,
            tier0_cache_mb,
            tier1_cache_mb,
            raft_batch_target,
            learner_count,
            compaction_rate_mbps,
            remote_prefetch_chunks,
        }
    }

    /// Explains to the operator why each derived parameter was selected.
    pub fn explain_config(intent: &OperatorIntentConfig, derived: &DerivedPhysicalConfig) -> Vec<String> {
        vec![
            format!("• Contract '{}': Rivero Profile '{}' with {}-bit LUTz bounds", intent.contract, derived.rivero_profile, derived.lutz_code_bits),
            format!("• Target p99 {}ms: ProofTree fanout {} with leaf cap {} for fast exact pruning", intent.p99_target_ms, derived.proof_tree_fanout, derived.proof_tree_leaf_capacity),
            format!("• Durability '{}' (max {}ms): Raft microbatch size target {}", intent.durability_mode, intent.max_commit_latency_ms, derived.raft_batch_target),
            format!("• Memory budget {}GB: Tier 0 Metadata {}MB, Tier 1 Vector Cache {}MB", intent.memory_budget_gb, derived.tier0_cache_mb, derived.tier1_cache_mb),
            format!("• Fault tolerance {}: Sized {} read learners for quorum safety and linearizable routing", intent.failure_tolerance, derived.learner_count),
        ]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_autoforge_calibration() {
        let profile = AutoForge::calibrate();
        assert!(profile.simd_gflops > 0.1);
        assert!(profile.memory_bandwidth_gbps > 0.01);
        assert!(profile.crossover_scale > 0.0);
    }

    #[test]
    fn test_autoforge_explain_config() {
        let intent = OperatorIntentConfig::default();
        let profile = AutoForge::calibrate();
        let derived = AutoForge::derive_physical_config(&intent, &profile);
        let explanation = AutoForge::explain_config(&intent, &derived);
        assert_eq!(explanation.len(), 5);
    }
}

