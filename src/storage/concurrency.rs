//! # LSM Segment Concurrency & Multi-Threaded Stress Harness
//!▫~•◦-------------------------------------------------------------------‣
//!
//! Provides a production-grade multi-threaded load test harness for [`SegmentedEngine`],
//! validating concurrent reader queries, writer insertions, deletions (tombstones), and
//! background compactions under high contention.
//!
//! ## Stated Invariants
//! 1. **Zero-Tombstone Leakage**: No tombstoned or deleted vector ID is ever returned by any reader.
//! 2. **Deadlock Immunity**: Writers, readers, and compactor threads proceed concurrently without livelock.
//! 3. **Linearizable Visibility**: Inserted items become visible across segment rotations.
