use std::sync::Arc;
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::thread;
use std::time::{Duration, Instant};

use crate::VectorEmbedding;
use crate::planning::planner::RetrievalContract;
use crate::storage::segment::SegmentedEngine;

/// Configuration parameters for the LSM Segment Concurrency Harness.
#[derive(Clone, Copy, Debug)]
pub struct LsmConcurrencyConfig {
    /// Number of concurrent reader threads performing searches.
    pub num_readers: usize,
    /// Number of concurrent writer threads performing inserts/deletes.
    pub num_writers: usize,
    /// Duration to run the concurrent stress test.
    pub duration: Duration,
    /// Target Top-K for reader queries.
    pub read_k: usize,
}

impl Default for LsmConcurrencyConfig {
    fn default() -> Self {
        Self {
            num_readers: 4,
            num_writers: 2,
            duration: Duration::from_millis(500),
            read_k: 10,
        }
    }
}

/// Comprehensive telemetry report generated by the LSM concurrency test.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct LsmConcurrencyReport {
    pub total_writes: usize,
    pub total_deletions: usize,
    pub total_reads: usize,
    pub write_qps: f64,
    pub read_qps: f64,
    pub read_p50_us: f64,
    pub read_p95_us: f64,
    pub read_p99_us: f64,
    pub tombstone_violations: usize,
    pub compactions_completed: usize,
}

fn percentile(mut xs: Vec<f64>, p: f64) -> f64 {
    if xs.is_empty() {
        return 0.0;
    }
    xs.sort_by(|a, b| a.total_cmp(b));
    let idx = ((xs.len() as f64 - 1.0) * (p / 100.0)).round() as usize;
    xs[idx.min(xs.len() - 1)]
}

/// Reusable concurrency harness primitive.
pub struct LsmSegmentConcurrencyHarness;

impl LsmSegmentConcurrencyHarness {
    /// Runs the concurrent multi-threaded stress benchmark across active and immutable segments.
    pub fn run(
        engine: Arc<SegmentedEngine>,
        test_vectors: Vec<VectorEmbedding>,
        config: LsmConcurrencyConfig,
    ) -> LsmConcurrencyReport {
        let stop_flag = Arc::new(AtomicBool::new(false));
        let total_writes = Arc::new(AtomicUsize::new(0));
        let total_deletions = Arc::new(AtomicUsize::new(0));
        let total_reads = Arc::new(AtomicUsize::new(0));
        let tombstone_violations = Arc::new(AtomicUsize::new(0));
        let compactions_completed = Arc::new(AtomicUsize::new(0));

        let dim = engine.dimension;
        let test_vectors = Arc::new(test_vectors);

        // Prepopulate baseline data
        for i in 0..100 {
            let v = if !test_vectors.is_empty() {
                test_vectors[i % test_vectors.len()].clone()
            } else {
                VectorEmbedding::from_complex(
                    (0..dim)
                        .map(|_| num_complex::Complex32::new(1.0, 0.0))
                        .collect(),
                )
                .into_normalized()
            };
            let _ = engine.insert(format!("base_{i}"), v);
        }

        let mut handles = Vec::new();
        let start_instant = Instant::now();

        // 1. Writer Threads (Insertions & Deletions)
        for w_idx in 0..config.num_writers {
            let engine_cloned = Arc::clone(&engine);
            let stop = Arc::clone(&stop_flag);
            let tw = Arc::clone(&total_writes);
            let td = Arc::clone(&total_deletions);
            let vecs = Arc::clone(&test_vectors);

            let handle = thread::spawn(move || {
                let mut op_counter = 0usize;
                while !stop.load(Ordering::Relaxed) {
                    op_counter += 1;
                    let item_id = format!("dyn_w{w_idx}_{op_counter}");
                    let v = if !vecs.is_empty() {
                        vecs[(w_idx * 1000 + op_counter) % vecs.len()].clone()
                    } else {
                        VectorEmbedding::from_complex(
                            (0..dim)
                                .map(|_| num_complex::Complex32::new(0.5, 0.0))
                                .collect(),
                        )
                        .into_normalized()
                    };

                    if engine_cloned.insert(item_id.clone(), v).is_ok() {
                        tw.fetch_add(1, Ordering::Relaxed);
                    }

                    // Periodically delete an item to test tombstone consistency
                    if op_counter % 5 == 0 {
                        let del_id = format!("dyn_w{w_idx}_{}", op_counter.saturating_sub(2));
                        if engine_cloned.delete(&del_id) {
                            td.fetch_add(1, Ordering::Relaxed);
                        }
                    }
                }
            });
            handles.push(handle);
        }

        // 2. Reader Threads
        let (lat_tx, lat_rx) = std::sync::mpsc::channel();

        for _r_idx in 0..config.num_readers {
            let engine_cloned = Arc::clone(&engine);
            let stop = Arc::clone(&stop_flag);
            let tr = Arc::clone(&total_reads);
            let tv = Arc::clone(&tombstone_violations);
            let vecs = Arc::clone(&test_vectors);
            let k = config.read_k;
            let tx = lat_tx.clone();

            let handle = thread::spawn(move || {
                let mut local_latencies = Vec::with_capacity(1024);
                let mut query_idx = 0usize;

                while !stop.load(Ordering::Relaxed) {
                    query_idx += 1;
                    let q = if !vecs.is_empty() {
                        &vecs[query_idx % vecs.len()]
                    } else {
                        &vecs[0]
                    };

                    let t0 = Instant::now();
                    let results =
                        engine_cloned.search_with_contract(q, k, RetrievalContract::Exact);
                    let lat_us = t0.elapsed().as_secs_f64() * 1_000_000.0;
                    local_latencies.push(lat_us);
                    tr.fetch_add(1, Ordering::Relaxed);

                    // Assert invariant: no empty IDs and valid scores
                    for (id, score) in results {
                        if id.is_empty() || !score.is_finite() {
                            tv.fetch_add(1, Ordering::Relaxed);
                        }
                    }
                }
                let _ = tx.send(local_latencies);
            });
            handles.push(handle);
        }
        drop(lat_tx);

        // 3. Background Compaction Thread
        {
            let engine_cloned = Arc::clone(&engine);
            let stop = Arc::clone(&stop_flag);
            let cc = Arc::clone(&compactions_completed);

            let handle = thread::spawn(move || {
                while !stop.load(Ordering::Relaxed) {
                    thread::sleep(Duration::from_millis(50));
                    if engine_cloned.compact().is_ok() {
                        cc.fetch_add(1, Ordering::Relaxed);
                    }
                }
            });
            handles.push(handle);
        }

        // Run for configured duration
        thread::sleep(config.duration);
        stop_flag.store(true, Ordering::Relaxed);

        for h in handles {
            let _ = h.join();
        }

        let elapsed_secs = start_instant.elapsed().as_secs_f64().max(0.001);
        let mut all_latencies = Vec::new();
        while let Ok(mut lats) = lat_rx.try_recv() {
            all_latencies.append(&mut lats);
        }

        let total_w = total_writes.load(Ordering::Relaxed);
        let total_d = total_deletions.load(Ordering::Relaxed);
        let total_r = total_reads.load(Ordering::Relaxed);
        let violations = tombstone_violations.load(Ordering::Relaxed);
        let compactions = compactions_completed.load(Ordering::Relaxed);

        LsmConcurrencyReport {
            total_writes: total_w,
            total_deletions: total_d,
            total_reads: total_r,
            write_qps: (total_w as f64) / elapsed_secs,
            read_qps: (total_r as f64) / elapsed_secs,
            read_p50_us: percentile(all_latencies.clone(), 50.0),
            read_p95_us: percentile(all_latencies.clone(), 95.0),
            read_p99_us: percentile(all_latencies, 99.0),
            tombstone_violations: violations,
            compactions_completed: compactions,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lsm_concurrency_harness_basic_execution() {
        let dim = 16;
        let engine = Arc::new(SegmentedEngine::new(dim, 20));
        let vectors: Vec<VectorEmbedding> = (0..50)
            .map(|i| {
                VectorEmbedding::from_complex(
                    (0..dim)
                        .map(|d| num_complex::Complex32::new((i + d) as f32, 0.0))
                        .collect(),
                )
                .into_normalized()
            })
            .collect();

        let report = LsmSegmentConcurrencyHarness::run(
            engine,
            vectors,
            LsmConcurrencyConfig {
                num_readers: 2,
                num_writers: 2,
                duration: Duration::from_millis(150),
                read_k: 5,
            },
        );

        assert!(
            report.total_writes > 0,
            "Writes should succeed concurrently"
        );
        assert!(report.total_reads > 0, "Reads should succeed concurrently");
        assert_eq!(
            report.tombstone_violations, 0,
            "Must have zero tombstone/data violations under concurrent load"
        );
    }
}
